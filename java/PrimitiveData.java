public class PrimitiveData {
    int n;
    float f;
    double d;
    char ch;
    boolean flag;

    public static void main(String[] args) {

        PrimitiveData obj = new PrimitiveData();
        System.out.println("int value: " + obj.n);
        System.out.println("float value: " + obj.f);
        System.out.println("double value: " + obj.d);
        System.out.println("char value: " + obj.ch);
        System.out.println("boolean value: " + obj.flag);
    }
}
